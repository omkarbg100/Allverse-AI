"""
PDF generator using reportlab — mirrors generatePdf.js (pdfkit).

Input data shape:
{
  "title": str,
  "subtitle": str,
  "sections": [{"heading": str, "points": [str, ...]}]
}
Returns: bytes (PDF binary)
"""

from io import BytesIO
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, HRFlowable
)
from reportlab.lib.enums import TA_CENTER, TA_LEFT


# ── Colour palette (matches pdfkit version) ────────────────────────
C_TITLE   = colors.HexColor("#111827")
C_SUBTITLE= colors.HexColor("#6B7280")
C_HEADING = colors.HexColor("#111827")
C_BODY    = colors.HexColor("#374151")
C_FOOTER  = colors.HexColor("#9CA3AF")
C_RULE    = colors.HexColor("#E5E7EB")


def generate_pdf(data: dict) -> bytes:
    """Build a styled PDF from the structured data dict and return bytes."""
    buf = BytesIO()

    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=50, rightMargin=50,
        topMargin=50,  bottomMargin=50,
        title=data.get("title", ""),
        author="NeuralHub",
        creator="NeuralHub",
    )

    # ── Styles ─────────────────────────────────────────────────────
    title_style = ParagraphStyle(
        "title", fontSize=28, alignment=TA_CENTER,
        textColor=C_TITLE, spaceAfter=6, leading=34,
    )
    subtitle_style = ParagraphStyle(
        "subtitle", fontSize=12, alignment=TA_CENTER,
        textColor=C_SUBTITLE, spaceAfter=20, leading=16,
    )
    heading_style = ParagraphStyle(
        "heading", fontSize=18, alignment=TA_LEFT,
        textColor=C_HEADING, spaceBefore=14, spaceAfter=6, leading=22,
        fontName="Helvetica-Bold",
    )
    bullet_style = ParagraphStyle(
        "bullet", fontSize=12, alignment=TA_LEFT,
        textColor=C_BODY, spaceAfter=5, leading=16, leftIndent=12,
    )
    footer_style = ParagraphStyle(
        "footer", fontSize=10, alignment=TA_CENTER,
        textColor=C_FOOTER, spaceBefore=24,
    )

    story = []

    # ── Title ──────────────────────────────────────────────────────
    story.append(Paragraph(data.get("title", ""), title_style))

    if data.get("subtitle"):
        story.append(Paragraph(data["subtitle"], subtitle_style))

    story.append(Spacer(1, 12))
    story.append(HRFlowable(width="100%", thickness=1, color=C_RULE))
    story.append(Spacer(1, 16))

    # ── Sections ───────────────────────────────────────────────────
    for section in data.get("sections", []):
        story.append(Paragraph(section.get("heading", ""), heading_style))
        for point in section.get("points", []):
            story.append(Paragraph(f"• &nbsp;{point}", bullet_style))
        story.append(Spacer(1, 8))

    # ── Footer ─────────────────────────────────────────────────────
    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=0.5, color=C_RULE))
    story.append(Paragraph("Generated by NeuralHub", footer_style))

    doc.build(story)
    return buf.getvalue()

