"""
PPTX generator using python-pptx — mirrors generatePpt.js (pptxgenjs).

Input data shape:
{
  "title": str,
  "subtitle": str,
  "slides": [{"title": str, "points": [str, ...]}]
}
Returns: bytes (PPTX binary)
"""

from io import BytesIO
from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN


# ── Colour palette (matches pptxgenjs version) ─────────────────────
C_PRIMARY   = RGBColor(0x25, 0x63, 0xEB)   # #2563EB  blue
C_SECONDARY = RGBColor(0x0F, 0x17, 0x2A)   # #0F172A  dark navy
C_TEXT      = RGBColor(0x33, 0x41, 0x55)   # #334155
C_LIGHT     = RGBColor(0xF8, 0xFA, 0xFC)   # #F8FAFC
C_BORDER    = RGBColor(0xE2, 0xE8, 0xF0)   # #E2E8F0
C_WHITE     = RGBColor(0xFF, 0xFF, 0xFF)
C_MUTED     = RGBColor(0x64, 0x74, 0x8B)   # #64748B
C_ACCENT    = RGBColor(0x60, 0xA5, 0xFA)   # #60A5FA  light blue
C_DBEAFE    = RGBColor(0xDB, 0xEA, 0xFE)
C_BFDBFE    = RGBColor(0xBF, 0xDB, 0xFE)
C_94A3B8    = RGBColor(0x94, 0xA3, 0xB8)
C_EFF6FF    = RGBColor(0xEF, 0xF6, 0xFF)


# ── Slide size: LAYOUT_WIDE 13.33" × 7.5" ─────────────────────────
SLIDE_W = Inches(13.33)
SLIDE_H = Inches(7.5)


def _set_bg(slide, color: RGBColor):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _add_textbox(slide, text: str, left, top, width, height,
                  font_size: int, bold=False, color: RGBColor = C_WHITE,
                  align=PP_ALIGN.LEFT):
    txb = slide.shapes.add_textbox(left, top, width, height)
    tf = txb.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.size = Pt(font_size)
    run.font.bold = bold
    run.font.color.rgb = color


def _add_rect(slide, left, top, width, height, fill_color: RGBColor, line_color: RGBColor | None = None):
    from pptx.util import Emu
    shape = slide.shapes.add_shape(
        1,  # MSO_SHAPE_TYPE.RECTANGLE
        left, top, width, height
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = fill_color
    if line_color:
        shape.line.color.rgb = line_color
        shape.line.width = Pt(0.5)
    else:
        shape.line.fill.background()
    return shape


# ── Cover slide ────────────────────────────────────────────────────

def _add_cover(prs: Presentation, data: dict):
    slide_layout = prs.slide_layouts[6]  # blank
    slide = prs.slides.add_slide(slide_layout)
    _set_bg(slide, C_PRIMARY)

    # top accent bar
    _add_rect(slide, Inches(0), Inches(0), SLIDE_W, Inches(0.18), C_ACCENT, C_ACCENT)

    # title
    _add_textbox(
        slide, data.get("title", ""),
        Inches(0.7), Inches(1.7), Inches(12), Inches(0.8),
        font_size=28, bold=True, color=C_WHITE, align=PP_ALIGN.CENTER,
    )

    # subtitle
    _add_textbox(
        slide, data.get("subtitle", ""),
        Inches(1), Inches(2.8), Inches(11.5), Inches(0.4),
        font_size=15, color=C_DBEAFE, align=PP_ALIGN.CENTER,
    )

    # footer
    _add_textbox(
        slide, "Generated by Allverse AI",
        Inches(0), Inches(6.9), SLIDE_W, Inches(0.2),
        font_size=10, color=C_BFDBFE, align=PP_ALIGN.CENTER,
    )


# ── Content slide ──────────────────────────────────────────────────

def _add_content_slide(prs: Presentation, title: str, points: list[str],
                        page: int, total: int):
    slide_layout = prs.slide_layouts[6]  # blank
    slide = prs.slides.add_slide(slide_layout)
    _set_bg(slide, C_WHITE)

    # slide title
    _add_textbox(
        slide, title,
        Inches(0.6), Inches(0.35), Inches(10), Inches(0.4),
        font_size=24, bold=True, color=C_PRIMARY,
    )

    # divider line
    line = slide.shapes.add_shape(1, Inches(0.6), Inches(0.85), Inches(12), Pt(1))
    line.fill.solid()
    line.fill.fore_color.rgb = C_BORDER
    line.line.fill.background()

    # bullet rows (max 6 points)
    visible = points[:6]
    for i, point in enumerate(visible):
        y = Inches(1.2 + i * 0.75)
        row_color = C_EFF6FF if i % 2 == 0 else C_LIGHT

        # row background
        _add_rect(slide, Inches(0.7), y, Inches(12), Inches(0.58),
                  row_color, C_BORDER)

        # bullet dot
        dot = slide.shapes.add_shape(
            9,  # MSO_SHAPE_TYPE.OVAL
            Inches(0.92), y + Inches(0.18), Inches(0.12), Inches(0.12)
        )
        dot.fill.solid()
        dot.fill.fore_color.rgb = C_PRIMARY
        dot.line.fill.background()

        # bullet text
        _add_textbox(
            slide, point,
            Inches(1.2), y + Inches(0.08), Inches(11), Inches(0.35),
            font_size=15, color=C_TEXT,
        )

    # page number
    _add_textbox(
        slide, f"{page}/{total}",
        Inches(12.1), Inches(6.9), Inches(0.8), Inches(0.2),
        font_size=10, color=C_MUTED, align=PP_ALIGN.RIGHT,
    )

    # branding
    _add_textbox(
        slide, "Allverse AI",
        Inches(0.6), Inches(6.9), Inches(2), Inches(0.2),
        font_size=10, color=C_MUTED,
    )


# ── Thank-you slide ────────────────────────────────────────────────

def _add_thank_you(prs: Presentation):
    slide_layout = prs.slide_layouts[6]  # blank
    slide = prs.slides.add_slide(slide_layout)
    _set_bg(slide, C_SECONDARY)

    _add_textbox(
        slide, "Thank You",
        Inches(0), Inches(2.2), SLIDE_W, Inches(0.8),
        font_size=34, bold=True, color=C_WHITE, align=PP_ALIGN.CENTER,
    )

    _add_textbox(
        slide, "Generated by Allverse AI",
        Inches(0), Inches(6.9), SLIDE_W, Inches(0.2),
        font_size=10, color=C_94A3B8, align=PP_ALIGN.CENTER,
    )


# ── Public entry ───────────────────────────────────────────────────

def generate_ppt(data: dict) -> bytes:
    """Build a styled PPTX from structured data and return bytes."""
    prs = Presentation()
    prs.slide_width  = SLIDE_W
    prs.slide_height = SLIDE_H

    _add_cover(prs, data)

    slides = data.get("slides", [])
    for i, s in enumerate(slides):
        _add_content_slide(prs, s.get("title", ""), s.get("points", []),
                            page=i + 1, total=len(slides))

    _add_thank_you(prs)

    buf = BytesIO()
    prs.save(buf)
    return buf.getvalue()

